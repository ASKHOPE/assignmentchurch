let currentLang = "en";
try {
  currentLang = localStorage.getItem("ward_agenda_lang") || "en";
} catch (e) {}

export function t(key, fallback = "") {
  const dict = translations[currentLang] || translations.en;
  return dict[key] || translations.en[key] || fallback || key;
}

export function getCurrentLang() {
  return currentLang;
}

export function setLanguage(lang) {
  currentLang = lang === "te" ? "te" : "en";
  try {
    localStorage.setItem("ward_agenda_lang", currentLang);
  } catch (e) {}
  document.documentElement.setAttribute("data-lang", currentLang);
  document.documentElement.setAttribute("lang", currentLang);
  applyTranslations();
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: currentLang } }));
}

export function applyTranslations() {
  const dict = translations[currentLang] || translations.en;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // Update language toggle button text
  const langIcon = document.getElementById("lang-icon");
  const langLabel = document.getElementById("lang-label");
  if (langIcon) langIcon.textContent = currentLang === "te" ? "EN" : "తె";
  if (langLabel) langLabel.textContent = currentLang === "te" ? "English" : "తెలుగు";
}

if (typeof window !== "undefined") {
  window.i18n = { t, setLanguage, getCurrentLang, applyTranslations, translations };
  document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();
  });
}
